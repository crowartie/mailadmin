// Работа с датами для календаря: ровно то, что не зависит ни от состояния страницы,
// ни от Vue. Раньше это жило внутри Calendar.vue вперемешку с раскладкой сетки и формой
// события, и поправить, скажем, начало недели было нельзя, не открывая файл на тысячу
// строк. Здесь всё проверяемо по отдельности и годится для повестки, задач и напоминаний.

export const DAYS = ['пн', 'вт', 'ср', 'чт', 'пт', 'сб', 'вс'];
export const DAYS_FULL = ['понедельник', 'вторник', 'среда', 'четверг', 'пятница', 'суббота', 'воскресенье'];
export const MONTHS = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];
export const MONTHS_N = ['Январь', 'Февраль', 'Март', 'Апрель', 'Май', 'Июнь', 'Июль', 'Август', 'Сентябрь', 'Октябрь', 'Ноябрь', 'Декабрь'];

/** Начало суток. */
export const day0 = (d) => { const x = new Date(d); x.setHours(0, 0, 0, 0); return x; };

/** Тот же день ± n суток. Через setDate — он сам разбирается с концом месяца и переводом часов. */
export const addDays = (d, n) => { const x = new Date(d); x.setDate(x.getDate() + n); return x; };

/** Понедельник недели, в которую попадает дата: неделя у нас начинается с него. */
export const monday = (d) => addDays(day0(d), -((d.getDay() + 6) % 7));

/** Один ли это календарный день. Сравниваем по частям, а не по времени: часовые пояса. */
export const sameDay = (a, b) => a.getFullYear() === b.getFullYear() && a.getMonth() === b.getMonth() && a.getDate() === b.getDate();

/** Дата как «2026-09-19» — в таком виде её ждёт сервер. */
export const ymd = (d) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;

/** Время как «09:30». */
export const hm = (d) => d.toLocaleTimeString('ru-RU', { hour: '2-digit', minute: '2-digit' });

/** «2026-09-19» → Date в местном поясе. Через new Date(строка) вышел бы UTC и сдвиг на сутки. */
export const parseDay = (s) => { const [y, m, d] = s.slice(0, 10).split('-').map(Number); return new Date(y, m - 1, d); };

/** Дата с временем 9:00 — с него начинается событие, созданное щелчком по дню. */
export const at9 = (d) => { const x = new Date(d); x.setHours(9, 0, 0, 0); return x; };

/** Подпись кнопки «+» в дне: «Создать событие: 18 сентября». */
export const addLabel = (d) => 'Создать событие: ' + d.toLocaleDateString('ru-RU', { day: 'numeric', month: 'long' });

/**
 * Цвет календаря в виде #RRGGBB. Календарь, заведённый с iPhone, хранит восьмизначный
 * код с прозрачностью (#RRGGBBAA): к нему дописывалась ещё пара знаков на полупрозрачный
 * фон события, получалось десять — такой цвет браузер не понимает, и событие оставалось
 * без фона. Заодно принимаем короткую запись (#RGB).
 */
export function hex6(c) {
    const v = String(c || '').trim();
    if (/^#[0-9a-f]{3}$/i.test(v)) return '#' + v[1] + v[1] + v[2] + v[2] + v[3] + v[3];
    if (/^#[0-9a-f]{6}([0-9a-f]{2})?$/i.test(v)) return v.slice(0, 7);

    return '#2F6FEB';
}
